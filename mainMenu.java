    private void tableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseClicked
        // TODO add your handling code here:
        if (evt.getClickCount() != 2)
            return;
    
        int viewRow = table.getSelectedRow();
        if (viewRow == -1) return;

        int row = table.convertRowIndexToModel(viewRow);
        DefaultTableModel products = (DefaultTableModel) table.getModel();
        DefaultTableModel cart = (DefaultTableModel) table1.getModel();

        String id = products.getValueAt(row, 0).toString();
        String name = products.getValueAt(row, 1).toString();
        double price = Double.parseDouble(products.getValueAt(row, 2).toString());
        int stock = Integer.parseInt(products.getValueAt(row, 3).toString());
        int addQty = (Integer) jSpinner1.getValue();

        int choice = JOptionPane.showConfirmDialog(this,
            "Add " + addQty + " x " + name + " to the cart?",
            "CONFIRM", JOptionPane.YES_NO_OPTION);
        if (choice != JOptionPane.YES_OPTION) return;

        for (int i = 0; i < cart.getRowCount(); i++) {
            if (cart.getValueAt(i, 0).toString().equals(id)) {
                int newQty = Integer.parseInt(cart.getValueAt(i, 1).toString()) + addQty;
                if (newQty > stock) {
                    JOptionPane.showMessageDialog(this, "Not enough stock. Available: " + stock);
                    return;
                }
                cart.setValueAt(newQty, i, 1);
                jSpinner1.setValue(1);
                updateTotal();
                return;
            }
        }

        if (addQty > stock) {
            JOptionPane.showMessageDialog(this, "Not enough stock. Available: " + stock);
            return;
        }
        cart.addRow(new Object[]{id, addQty, name, price});
        jSpinner1.setValue(1);
        updateTotal();
    }//GEN-LAST:event_tableMouseClicked

