    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
        // TODO add your handling code here: 
        int viewRow = table.getSelectedRow();
        if (viewRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a product first.");
            return;
        }

        int row = table.convertRowIndexToModel(viewRow);
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        String id = model.getValueAt(row, 0).toString();

        javax.swing.JTextField nameField  = new javax.swing.JTextField(model.getValueAt(row, 1).toString());
        javax.swing.JTextField priceField = new javax.swing.JTextField(model.getValueAt(row, 2).toString());
        javax.swing.JTextField stockField = new javax.swing.JTextField(model.getValueAt(row, 3).toString());

        Object[] form = {
            "Product name:", nameField,
            "Price:", priceField,
            "Stock:", stockField
        };

        int choice = JOptionPane.showConfirmDialog(this, form, "Update Product",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (choice != JOptionPane.OK_OPTION) return;

        String newName = nameField.getText().trim();
        double newPrice;
        int newStock;

        try {
            newPrice = Double.parseDouble(priceField.getText().trim());
            newStock = Integer.parseInt(stockField.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Price and stock must be numbers.");
            return;
        }

        if (newName.isEmpty() || newPrice < 0 || newStock < 0) {
            JOptionPane.showMessageDialog(this, "Please enter a name, and a price and stock of 0 or more.");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to UPDATE this product?\n\n"
            + "Name: " + newName + "\n"
            + "Price: " + newPrice + "\n"
            + "Stock: " + newStock,
            "CONFIRM UPDATE", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        String sql = "UPDATE products SET product_name = ?, product_price = ?, product_quantity = ? WHERE id = ?";

        try (Connection con = DriverManager.getConnection(
                    "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
                PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, newName);
            ps.setDouble(2, newPrice);
            ps.setInt(3, newStock);
            ps.setInt(4, Integer.parseInt(id));
            ps.executeUpdate();

            DefaultTableModel cart = (DefaultTableModel) table1.getModel();
            for (int i = cart.getRowCount() - 1; i >= 0; i--) {
                if (cart.getValueAt(i, 0).toString().equals(id)) {
                    cart.removeRow(i);
                }
            }
            updateTotal();

            loadTable();
            JOptionPane.showMessageDialog(this, "Product updated!");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_updateActionPerformed

