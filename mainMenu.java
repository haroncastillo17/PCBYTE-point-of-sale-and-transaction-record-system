    private void placeOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_placeOrderActionPerformed
        // TODO add your handling code here:
        DefaultTableModel cart = (DefaultTableModel) table1.getModel();

        if (cart.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "The cart is empty.");
            return;
        }
        
        double orderTotal = 0;
        for (int i = 0; i < cart.getRowCount(); i++) {
            orderTotal += Integer.parseInt(cart.getValueAt(i, 1).toString())
                        * Double.parseDouble(cart.getValueAt(i, 3).toString());
    }
        orderTotal = Math.round(orderTotal * 100.0) / 100.0;

        Object[] options = {"Place Order", "Add More Products"};
        int choice = JOptionPane.showOptionDialog(this,
                String.format("Total: %.2f%n%nDo you want to place this order or add more products?", orderTotal),
                "CONFIRM ORDER",
                JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE,
                null, options, options[0]);
        if (choice != 0) return;

        double payment;
        while (true) {
            String input = JOptionPane.showInputDialog(this,
                    String.format("Total: %.2f%n%nEnter the customer's payment:", orderTotal),
                   "PAYMENT", JOptionPane.PLAIN_MESSAGE);
            if (input == null) return;

            try {
                payment = Double.parseDouble(input.trim());
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Payment must be a number.");
                continue;
            }
            if (payment < orderTotal) {
                JOptionPane.showMessageDialog(this, "Payment is less than the total.");
                continue;
            }
            break;
        }
        double change = Math.round((payment - orderTotal) * 100.0) / 100.0;

        String stockSql  = "UPDATE products SET product_quantity = product_quantity - ? "
                        + "WHERE id = ? AND product_quantity >= ?";
        String insertSql = "INSERT INTO `transaction` "
                        + "(cashier, product, quantity, price, total_price, product_payment, payment_change, `date`) "
                        + "VALUES (?, ?, ?, ?, ?, ?, ?, NOW())";

        try (Connection con = DriverManager.getConnection(
                    "jdbc:mysql://localhost:3306/pcbyte_db", "root", "")) {

            con.setAutoCommit(false);

            try (PreparedStatement stock = con.prepareStatement(stockSql);
                 PreparedStatement ins   = con.prepareStatement(insertSql)) {

                for (int i = 0; i < cart.getRowCount(); i++) {
                    int productId = Integer.parseInt(cart.getValueAt(i, 0).toString());
                    int qty = Integer.parseInt(cart.getValueAt(i, 1).toString());
                    String name = cart.getValueAt(i, 2).toString();
                    double price = Double.parseDouble(cart.getValueAt(i, 3).toString());

                    stock.setInt(1, qty);
                    stock.setInt(2, productId);
                    stock.setInt(3, qty);
                    if (stock.executeUpdate() == 0) {
                        throw new SQLException("Not enough stock for \"" + name + "\".");
                    }

                    ins.setString(1, welcomeName);
                    ins.setString(2, name);
                    ins.setInt(3, qty);
                    ins.setDouble(4, price);
                    ins.setDouble(5, Math.round(qty * price * 100.0) / 100.0);
                    if (i == cart.getRowCount() - 1) {
                    ins.setDouble(6, payment);
                    ins.setDouble(7, change);
                    } else {
                    ins.setNull(6, java.sql.Types.DOUBLE);
                    ins.setNull(7, java.sql.Types.DOUBLE);
                    }
                    ins.executeUpdate();
                    }

                con.commit();

            } catch (SQLException ex) {
                con.rollback();
                throw ex;
            }

            JOptionPane.showMessageDialog(this, String.format(
                    "Order placed!%n%nTotal: %.2f%nPayment: %.2f%nChange: %.2f",
                    orderTotal, payment, change),
                    "CHANGE", JOptionPane.INFORMATION_MESSAGE);

            cart.setRowCount(0);
            updateTotal();
            loadTable();

        } catch (SQLException | NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Order failed: " + e.getMessage());
        }
    }//GEN-LAST:event_placeOrderActionPerformed

