    private void loadCashTable() {
        DefaultTableModel model = (DefaultTableModel) cashTable.getModel();
        model.setRowCount(0);

        String sql = "SELECT id, first_name, middle_name, last_name, password, username, role "
                   + "FROM users WHERE active = 1";

        try (Connection con = DriverManager.getConnection(
                     "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("first_name"),
                    rs.getString("middle_name"),
                    rs.getString("last_name"),
                    rs.getString("username"),
                    rs.getString("password"),
                    rs.getString("role")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    
    private void removeEmpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeEmpActionPerformed
        // TODO add your handling code here:
        int viewRow = cashTable.getSelectedRow();
        if (viewRow == -1) {
            JOptionPane.showMessageDialog(this, "Select an employee first.");
            return;
        }

        int modelRow = cashTable.convertRowIndexToModel(viewRow);
        DefaultTableModel model = (DefaultTableModel) cashTable.getModel();
        String id = model.getValueAt(modelRow, 0).toString();
        String fName = model.getValueAt(modelRow, 1).toString();
        String username = model.getValueAt(modelRow, 4).toString();

        if (username.equals(welcomeName)) {
            JOptionPane.showMessageDialog(this, "You can't remove the account you're logged in with.");
            return;
        }

        int choice = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to REMOVE \"" + fName + "\"?",
                "CONFIRM REMOVE", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (choice != JOptionPane.YES_OPTION) return;

    try (Connection con = DriverManager.getConnection(
                    "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
             PreparedStatement ps = con.prepareStatement(
                    "UPDATE users SET active = 0 WHERE id = ?")) {

            ps.setInt(1, Integer.parseInt(id));
            ps.executeUpdate();

            loadCashTable();
            JOptionPane.showMessageDialog(this, "Employee removed.");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            }
    }//GEN-LAST:event_removeEmpActionPerformed

