    private void updateEmpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateEmpActionPerformed
        // TODO add your handling code here:
        if (!welcomeName.equals("admin")) {
            JOptionPane.showMessageDialog(this, "Admin only.");
            return;
        }

        int viewRow = cashTable.getSelectedRow();
        if (viewRow == -1) {
            JOptionPane.showMessageDialog(this, "Select an employee first.");
            return;
        }

        int row = cashTable.convertRowIndexToModel(viewRow);
        DefaultTableModel model = (DefaultTableModel) cashTable.getModel();
        String id = model.getValueAt(row, 0).toString();

        javax.swing.JTextField firstName  = new javax.swing.JTextField(String.valueOf(model.getValueAt(row, 1)));
        javax.swing.JTextField middleName = new javax.swing.JTextField(
                model.getValueAt(row, 2) == null ? "" : model.getValueAt(row, 2).toString());
        javax.swing.JTextField lastName   = new javax.swing.JTextField(String.valueOf(model.getValueAt(row, 3)));
        javax.swing.JTextField userName   = new javax.swing.JTextField(String.valueOf(model.getValueAt(row, 4)));
        javax.swing.JPasswordField password = new javax.swing.JPasswordField();

        Object[] form = {
            "First Name: ", firstName,
            "Middle Name: ", middleName,
            "Last Name: ", lastName,
            "Username: ", userName,
            "New Password: ", password
        };

        int choice = JOptionPane.showConfirmDialog(this, form, "Update Employee",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (choice != JOptionPane.OK_OPTION) return;

        String newName  = firstName.getText().trim();
        String newMname = middleName.getText().trim();
        String newLname = lastName.getText().trim();
        String newUname = userName.getText().trim();
        String newPass  = new String(password.getPassword()).trim();

        if (newName.isEmpty() || newMname.isEmpty() || newLname.isEmpty() || newUname.isEmpty() ) {
            JOptionPane.showMessageDialog(this,
                    "First name, middle name, last name, and usernamee are required.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to UPDATE this employee?\n\n"
                + "First Name: " + newName + "\n"
                + "Middle Name: " + newMname + "\n"
                + "Last Name: " + newLname + "\n"
                + "Username: " + newUname + "\n"
                + (newPass.isEmpty() ? "" : "\nPassword: will be changed"),
                "CONFIRM UPDATE", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        String sql = newPass.isEmpty()
            ? "UPDATE users SET first_name = ?, middle_name = ?, last_name = ?, username = ? WHERE id = ?"
            : "UPDATE users SET first_name = ?, middle_name = ?, last_name = ?, username = ?, password = ? WHERE id = ?";

        try (Connection con = DriverManager.getConnection(
                    "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
            PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, newName);
            ps.setString(2, newMname);
            ps.setString(3, newLname);
            ps.setString(4, newUname);
            if (newPass.isEmpty()) {
                ps.setInt(5, Integer.parseInt(id));
            } else {
                ps.setString(5, newPass);
                ps.setInt(6, Integer.parseInt(id));
            }
            ps.executeUpdate();

            loadCashTable();
            JOptionPane.showMessageDialog(this, "Employee updated!");
    
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_updateEmpActionPerformed

