    private void addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addActionPerformed
String pn = productname.getText().trim();
String pp = productprice.getText().trim();
String pq = productquantity.getText().trim();

if (pn.isEmpty() || pp.isEmpty() || pq.isEmpty()){
    JOptionPane.showMessageDialog(this, "Please fill in all fields!", "WARNING", JOptionPane.WARNING_MESSAGE);
    return;
}

Connection conn = DBConnection.connect();

try{
    double price = Double.parseDouble(pp);
    int quantity = Integer.parseInt(pq);
    
    //Connection conn = DBConnection.connect();
    String sql = "INSERT INTO products (product_name, product_price, product_quantity) VALUES (?,?,?)";
    PreparedStatement pstmt = conn.prepareStatement(sql);
    pstmt.setString(1, pn);
    pstmt.setString(2, pp);
    pstmt.setString(3, pq);
    int rows = pstmt.executeUpdate();
    if (rows > 0 ){
        JOptionPane.showMessageDialog(this, "Product is added successfully!");
        productname.setText("");
        productprice.setText("");
        productquantity.setText("");
    }
    
    conn.close();
}catch (NumberFormatException e){
    JOptionPane.showMessageDialog(this, "Price and Quantity must be numbers!", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}catch (Exception e){
    JOptionPane.showMessageDialog(this, "Database Error:" + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}
    
        
        int choice  = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to ADD?",
        "CONFIRM",
        JOptionPane.YES_NO_OPTION
                 
    );
        if (choice == JOptionPane.YES_OPTION) {
        mainMenu backMenu = new mainMenu(loggedName);
        backMenu.setVisible(true);
        this.dispose();
     } // TODO add your handling code here:
    }//GEN-LAST:event_addActionPerformed

