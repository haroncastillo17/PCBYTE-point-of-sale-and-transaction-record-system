    private void cashierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cashierActionPerformed
        String fn =firstname.getText();
        String mn =middlename.getText();
        String ln =lastname.getText();
        String un =username.getText();
        String pw =new String(password.getPassword());
      
        try{
            java.sql.Connection conn = DBConnection.connect();

            String sql = "INSERT INTO users (first_name,middle_name,last_name,username,password,role) VALUES (?,?,?,?,?,?)";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);

            pst.setString(1, fn);
            pst.setString(2, mn);
            pst.setString(3, ln);
            pst.setString(4, un);
            pst.setString(5, pw);
            pst.setString(6, "cashier");

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Cashier Registered Successfully!");
            new mainMenu(loggedName).setVisible(true);
            this.dispose();

            conn.close();
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Error:" + e.getMessage());
        }

        if  (fn.isEmpty()|| mn.isEmpty() || ln.isEmpty() || un.isEmpty() || pw.isEmpty()){
            JOptionPane.showMessageDialog(this, " Please fill out the form!");
            return;
        }else{
            JOptionPane.showMessageDialog(this, " REGISTERED!! ");
            new mainMenu(loggedName). setVisible(true);
            this. dispose();
        }
        new mainMenu(loggedName). setVisible(true);
        this. dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_cashierActionPerformed

