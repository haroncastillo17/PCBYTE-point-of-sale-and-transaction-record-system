    private void transTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_transTableMouseClicked
        // TODO add your handling code here:
        if (evt.getClickCount() != 2) return;

        if (!loggedName.equals("admin")) {
            JOptionPane.showMessageDialog(this, "Admin only.");
            return;
        }

        int viewRow = transTable.getSelectedRow();
        if (viewRow == -1) return;

        int row = transTable.convertRowIndexToModel(viewRow);
        DefaultTableModel model = (DefaultTableModel) transTable.getModel();
        int id = Integer.parseInt(model.getValueAt(row, 0).toString());
        Object product = model.getValueAt(row, 2);
        Object quantity = model.getValueAt(row, 3);

        int choice = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this record?\n" + product + " x " + quantity,
                "CONFIRM", JOptionPane.YES_NO_OPTION);
        if (choice != JOptionPane.YES_OPTION) return;

        try (Connection con = DriverManager.getConnection(
                     "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
            PreparedStatement ps = con.prepareStatement(
                     "DELETE FROM `transaction` WHERE id = ?")) {

            ps.setInt(1, id);
            ps.executeUpdate();

            loadTransactions();
            JOptionPane.showMessageDialog(this, "Record deleted.");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_transTableMouseClicked

    private void clearTransActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_clearTransActionPerformed
        // TODO add your handling code here:
        int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to CLEAR ALL transaction records?\n\n"
            + "This permanently deletes every sale from the database\n"
            + "and cannot be undone.",
            "CONFIRM CLEAR", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (confirm != JOptionPane.YES_OPTION) return;

        try (Connection con = DriverManager.getConnection(
                "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
            Statement st = con.createStatement()) {

            st.executeUpdate("DELETE FROM `transaction`");
            st.executeUpdate("ALTER TABLE `transaction` AUTO_INCREMENT = 1");

            ((DefaultTableModel) transTable.getModel()).setRowCount(0);
            JOptionPane.showMessageDialog(this, "All transaction records were cleared.");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            }
    }//GEN-LAST:event_clearTransActionPerformed

    private void loadTransactions() {
        DefaultTableModel trans = (DefaultTableModel) transTable.getModel();
        trans.setRowCount(0);

        String sql = "SELECT id, cashier, product, quantity, price, total_price, product_payment, payment_change, `date` "
           + "FROM `transaction` ORDER BY `date` DESC";

        try (Connection con = DriverManager.getConnection(
                     "jdbc:mysql://localhost:3306/pcbyte_db", "root", "");
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                trans.addRow(new Object[]{
                    rs.getInt("id"),
                    rs.getString("cashier"),
                    rs.getString("product"),
                    rs.getInt("quantity"),
                    rs.getDouble("price"),
                    rs.getDouble("total_price"),
                    rs.getObject("product_payment"),
                    rs.getObject("payment_change"),
                    rs.getTimestamp("date")
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    
