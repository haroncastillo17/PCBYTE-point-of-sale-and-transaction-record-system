    private void submitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitActionPerformed
    String uN = username.getText();
    String pW = new String(password.getPassword());
   
    if (uN.isEmpty() || pW.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter username and password");
        return;
    }
        String selectedRole="";
        if (adminRButton.isSelected()){
           selectedRole = "admin";
        }else if (cashierRButton.isSelected()){
           selectedRole = "cashier";
        }else{
            JOptionPane.showMessageDialog(this, "Please select Admin or Cashier", "WARNING", JOptionPane.WARNING_MESSAGE);
            return;
        }
            try{
                java.sql.Connection conn = DBConnection.connect();
               
                String sql = "SELECT * FROM users WHERE username=? AND password=? AND role=?";
                java.sql.PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, uN);
                pst.setString(2, pW);
                pst.setString(3, selectedRole);
               
                java.sql.ResultSet rs = pst.executeQuery();
               
                if (rs.next()){
                    JOptionPane.showMessageDialog(this, "LOGIN SUCCESSFUL!");
                    mainMenu login = new mainMenu(uN);
                    login.setVisible(true);
                    this.dispose();
                }else{
                    JOptionPane.showMessageDialog(this, "Invalid Username, Password or Role!", "WARNING", JOptionPane.WARNING_MESSAGE);
                    }
                conn.close();
               
                }catch(Exception e){
             JOptionPane.showMessageDialog(this, "Database Error:" + e.getMessage());
        }
    }//GEN-LAST:event_submitActionPerformed

